export const messages = { en, cs };
export type Locale = "en" | "cs";

function czechPlural(choice: number): number {
  if (choice === 0) return 0;
  if (choice === 1) return 1;
  if (choice >= 2 && choice <= 4) return 2;
  return 3;
}

export function createAppI18n(locale: Locale = "en") {
  return createI18n({
    legacy: false,
    locale,
    fallbackLocale: "en",
    messages,
    pluralRules: { cs: czechPlural },
  });
}
